  function storageGet() {
    try { return localStorage.getItem(STORAGE_KEY); } catch (e) { return null; }
  }
  function storageSet(v) {
    try { localStorage.setItem(STORAGE_KEY, v); } catch (e) { /* storage unavailable: language lasts for this page view */ }
  }

  // A static export may carry the language it was exported in; the viewer's own choice wins.
  const exported = document.documentElement.getAttribute("data-lang");
  let lang = LANGS.includes(storageGet()) ? storageGet() : LANGS.includes(exported) ? exported : "cs";

  function t(text, params) {
    let out = lang === "en" && Object.prototype.hasOwnProperty.call(EN, text) ? EN[text] : text;
    if (params) out = out.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));
    return out;
  }

  // plural(n, ["1 commit", "2–4 commity", "5+ commitů"]) picks the Czech form; English uses
  // the dictionary entry of the first form ("{n} commit") and of the last one for n ≠ 1.
  const csRules = new Intl.PluralRules("cs-CZ");
  function plural(n, forms, params) {
    const p = Object.assign({ n: n }, params || {});
    if (lang === "en") return t(n === 1 ? forms[0] : forms[forms.length - 1], p).replace(/\{n\}/g, String(n));
    const cat = csRules.select(n);
    const form = cat === "one" ? forms[0] : cat === "few" ? forms[1] : forms[2] || forms[1];
    return t(form, p);
  }

  const listeners = [];
  function setLang(next) {
    if (!LANGS.includes(next) || next === lang) return;
    lang = next;
    storageSet(next);
    document.documentElement.lang = next;
    listeners.forEach((f) => f(next));
  }

  // Elements with data-i18n (static markup in index.html) are translated in place.
  function translateStatic(root) {
    (root || document).querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    (root || document).querySelectorAll("[data-i18n-label]").forEach((el) => {
      el.setAttribute("aria-label", t(el.getAttribute("data-i18n-label")));
    });
  }

  document.documentElement.lang = lang;
  window.I18N = {
    t, plural, setLang, translateStatic,
    lang: () => lang,
    locale: () => LOCALES[lang],
    onChange: (f) => listeners.push(f),
    LANGS,
    _dict: EN,
  };
